#!/usr/bin/env python3
"""Generates the EmuBuddy app icon from a 32x32 pixel-art design.

Writes (no third-party modules needed):
  emubuddy/lib/emubuddyicon.png   1024x1024
  emubuddy/lib/emubuddyicon.icns  (macOS, needs `iconutil`)
  emubuddy/lib/emubuddyicon.ico   (Windows, PNG-compressed entries)
  emubuddy/src/emubuddy_icon.h    128x128 RGBA for SDL_SetWindowIcon

Run from the repository root:  python3 tools/make_icon.py
"""
import os, struct, subprocess, sys, tempfile, zlib

N = 32
T = (0, 0, 0, 0)
BLUE = (34, 34, 255, 255)        # IIgs desktop blue
BLUE_D = (20, 20, 170, 255)      # lower edge shade
BLUE_L = (96, 96, 255, 255)      # top highlight
CREAM = (240, 236, 222, 255)     # monitor case
SHADE = (200, 196, 180, 255)
DARK = (40, 40, 48, 255)
SCREEN = (200, 238, 255, 255)
LED = (60, 210, 90, 255)
FACE = (20, 20, 40, 255)

px = [[T] * N for _ in range(N)]


def put(x, y, c):
    if 0 <= x < N and 0 <= y < N:
        px[y][x] = c


def rect(x0, y0, x1, y1, c):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            put(x, y, c)


# rounded-square background
for y in range(2, 30):
    for x in range(2, 30):
        dx = max(2 + 5 - x, x - (29 - 5), 0)
        dy = max(2 + 5 - y, y - (29 - 5), 0)
        if dx * dx + dy * dy <= 25:
            put(x, y, BLUE)
rect(7, 2, 24, 2, BLUE_L)
rect(7, 29, 24, 29, BLUE_D)

# monitor: outline, case, bezel, screen
rect(6, 5, 25, 22, DARK)
rect(7, 6, 24, 21, CREAM)
rect(7, 21, 24, 21, SHADE)
rect(24, 6, 24, 21, SHADE)
rect(9, 8, 22, 18, DARK)
rect(10, 9, 21, 17, SCREEN)
# smiley on the screen
rect(12, 11, 13, 12, FACE)
rect(18, 11, 19, 12, FACE)
put(12, 14, FACE); put(19, 14, FACE)
rect(13, 15, 18, 15, FACE)
# power LED and floppy slot on the chin
rect(20, 20, 21, 20, LED)
rect(9, 20, 15, 20, SHADE)
# stand and base
rect(12, 23, 19, 23, DARK)
rect(13, 23, 18, 23, SHADE)
rect(9, 24, 22, 25, DARK)
rect(10, 24, 21, 24, CREAM)
rect(10, 25, 21, 25, SHADE)


def scaled(size):
    """RGBA rows for `size` x `size` (integer upscale, or 2x2 average)."""
    rows = []
    if size >= N:
        k = size // N
        for y in range(size):
            row = []
            for x in range(size):
                row.append(px[y // k][x // k])
            rows.append(row)
    else:                        # 16: average 2x2 blocks (premultiplied)
        for y in range(size):
            row = []
            for x in range(size):
                cs = [px[2 * y + j][2 * x + i] for j in (0, 1) for i in (0, 1)]
                a = sum(c[3] for c in cs)
                if a == 0:
                    row.append(T)
                else:
                    row.append(tuple(sum(c[k] * c[3] for c in cs) // a
                                     for k in range(3)) + (a // 4,))
            rows.append(row)
    return rows


def png(size):
    rows = scaled(size)
    raw = b"".join(b"\x00" + b"".join(bytes(p) for p in r) for r in rows)

    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)

    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw, 9))
            + chunk(b"IEND", b""))


root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
lib = os.path.join(root, "emubuddy", "lib")
src = os.path.join(root, "emubuddy", "src")

open(os.path.join(lib, "emubuddyicon.png"), "wb").write(png(1024))

# Windows .ico with PNG entries
sizes = [16, 32, 64, 128, 256]
data = [png(s) for s in sizes]
ico = struct.pack("<HHH", 0, 1, len(sizes))
off = 6 + 16 * len(sizes)
for s, d in zip(sizes, data):
    ico += struct.pack("<BBBBHHII", s % 256, s % 256, 0, 0, 1, 32, len(d), off)
    off += len(d)
open(os.path.join(lib, "emubuddyicon.ico"), "wb").write(ico + b"".join(data))

# macOS .icns through iconutil
if sys.platform == "darwin":
    with tempfile.TemporaryDirectory() as t:
        iset = os.path.join(t, "emubuddy.iconset")
        os.mkdir(iset)
        for base in (16, 32, 128, 256, 512):
            open(os.path.join(iset, "icon_%dx%d.png" % (base, base)), "wb").write(png(base))
            open(os.path.join(iset, "icon_%dx%d@2x.png" % (base, base)), "wb").write(png(base * 2))
        subprocess.check_call(["iconutil", "-c", "icns", iset, "-o",
                               os.path.join(lib, "emubuddyicon.icns")])
else:
    print("not on macOS: emubuddyicon.icns not regenerated")

# 128x128 RGBA header for the window icon
rows = scaled(128)
flat = [v for r in rows for p in r for v in p]
with open(os.path.join(src, "emubuddy_icon.h"), "w") as f:
    f.write("/* Generated by tools/make_icon.py -- do not edit. EmuBuddy window\n"
            " * icon (RGBA) for SDL_SetWindowIcon. */\n"
            "#ifndef EMUBUDDY_ICON_H\n#define EMUBUDDY_ICON_H\n\n"
            "static const int emubuddy_icon_width = 128;\n"
            "static const int emubuddy_icon_height = 128;\n"
            "static const unsigned char emubuddy_icon_rgba[%d] = {\n" % len(flat))
    for i in range(0, len(flat), 16):
        f.write("  " + ",".join(str(v) for v in flat[i:i + 16]) + ",\n")
    f.write("};\n\n#endif\n")
print("icons written")
