#!/usr/bin/env python3
"""Writes emubuddy/src/receive_bin.h from the assembled tools/receive/build/Receive,
so EmuBuddy can offer it (Disks > Copy Receive to Shared Folder). Run
tools/receive/build.sh first, then this script, from anywhere."""
import os
here = os.path.dirname(os.path.abspath(__file__))
data = open(os.path.join(here, "build", "Receive"), "rb").read()
out = os.path.join(here, "..", "..", "emubuddy", "src", "receive_bin.h")
with open(out, "w") as f:
    f.write("/* Generated by tools/receive/embed.py: the GS/OS program Receive (tools/receive). */\n"
            "#ifndef EMUBUDDY_RECEIVE_BIN_H\n#define EMUBUDDY_RECEIVE_BIN_H\n\n"
            "static const unsigned char receive_bin[%d] = {\n" % len(data))
    for i in range(0, len(data), 16):
        f.write("  " + ",".join("0x%02x" % b for b in data[i:i+16]) + ",\n")
    f.write("};\n\n#endif\n")
print("wrote", out, len(data), "bytes")
