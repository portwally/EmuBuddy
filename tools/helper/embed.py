#!/usr/bin/env python3
"""Writes emubuddy/src/helper_bin.h from the assembled tools/helper/build/EmuBuddyHelper,
so EmuBuddy can offer it (installed into the boot disk). Run
tools/helper/build.sh first, then this script, from anywhere."""
import os
here = os.path.dirname(os.path.abspath(__file__))
data = open(os.path.join(here, "build", "EmuBuddyHelper"), "rb").read()
out = os.path.join(here, "..", "..", "emubuddy", "src", "helper_bin.h")
with open(out, "w") as f:
    f.write("/* Generated by tools/helper/embed.py: the GS/OS program EmuBuddyHelper (tools/helper). */\n"
            "#ifndef EMUBUDDY_HELPER_BIN_H\n#define EMUBUDDY_HELPER_BIN_H\n\n"
            "static const unsigned char helper_bin[%d] = {\n" % len(data))
    for i in range(0, len(data), 16):
        f.write("  " + ",".join("0x%02x" % b for b in data[i:i+16]) + ",\n")
    f.write("};\n\n#endif\n")
print("wrote", out, len(data), "bytes")
