#!/usr/bin/env python3
"""EmuBuddy ships GSGate, the web gateway for IIgs browsers, inside the program.

    tools/gateway/embed.py [folder with the newest gsgate.py and gspic.py]

With a folder: copies the two files from there into tools/gateway/ first (the gateway is developed
next to the IIgs browser, outside this repository). Then writes emubuddy/src/gateway_py.h from the
copies in tools/gateway/. Run it after every change to the gateway, from anywhere."""
import os
import shutil
import sys

here = os.path.dirname(os.path.abspath(__file__))
FILES = ("gsgate.py", "gspic.py")
if len(sys.argv) > 1:
    for name in FILES:
        shutil.copyfile(os.path.join(sys.argv[1], name), os.path.join(here, name))
out = os.path.join(here, "..", "..", "emubuddy", "src", "gateway_py.h")
with open(out, "w") as f:
    f.write("/* Generated by tools/gateway/embed.py from the two Python files in tools/gateway: GSGate, the web gateway\n"
            " * for IIgs browsers (a Python program that EmuBuddy writes out and starts). */\n"
            "#ifndef EMUBUDDY_GATEWAY_PY_H\n#define EMUBUDDY_GATEWAY_PY_H\n\n")
    for name in FILES:
        data = open(os.path.join(here, name), "rb").read()
        sym = name.replace(".", "_")
        f.write("static const unsigned char %s[%d] = {\n" % (sym, len(data)))
        for i in range(0, len(data), 20):
            f.write("  " + ",".join("%d" % b for b in data[i:i + 20]) + ",\n")
        f.write("};\n\n")
        print("%s: %d bytes" % (name, len(data)))
    f.write("#endif\n")
print("wrote", os.path.normpath(out))
