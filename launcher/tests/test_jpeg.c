static int	g_fail;

static void
check(int ok, const char *what)
{
	if(!ok) {
		printf("FAIL: %s\n", what);
		g_fail++;
	}
}

static void
picture(const unsigned char *d, size_t n, const char *name, int tol)
{
	int		w = 0, h = 0, worst = 0;
	unsigned char	*p = jpeg_decode(d, n, &w, &h);
	char		msg[100];

	snprintf(msg, sizeof(msg), "%s decodes", name);
	check(p != NULL, msg);
	if(!p) {
		return;
	}
	snprintf(msg, sizeof(msg), "%s is 24x24", name);
	check(w == 24 && h == 24, msg);
	for(int y = 0; y < h && w == 24; y++) {
		for(int x = 0; x < w; x++) {
			int want[3] = { x * 10, y * 10, 200 - (x + y) * 4 };

			for(int c = 0; c < 3; c++) {
				int diff = abs(p[(y * w + x) * 4 + c] - want[c]);

				worst = diff > worst ? diff : worst;
			}
			check(p[(y * w + x) * 4 + 3] == 255, "alpha is 255");
		}
	}
	snprintf(msg, sizeof(msg), "%s colours are right (worst difference %d)", name, worst);
	check(worst <= tol, msg);
	free(p);
}

int
main(void)
{
	unsigned char	junk[64], *cut;
	int		w, h;

	picture(g_base, sizeof(g_base), "baseline", 24);
	picture(g_prog, sizeof(g_prog), "progressive", 12);
	check(jpeg_is(g_base, sizeof(g_base)), "jpeg_is knows a JPEG");
	memset(junk, 0x42, sizeof(junk));
	check(!jpeg_is(junk, sizeof(junk)), "jpeg_is refuses other data");
	check(jpeg_decode(junk, sizeof(junk), &w, &h) == NULL, "other data is refused");
	check(jpeg_decode(g_base, 20, &w, &h) == NULL, "a file cut off in the header is refused");
	/* cut off in the picture data: no crash (a partial picture or NULL are both fine) */
	cut = jpeg_decode(g_prog, sizeof(g_prog) / 2, &w, &h);
	free(cut);
	printf(g_fail ? "%d test(s) failed\n" : "jpeg: all tests passed\n", g_fail);
	return g_fail ? 1 : 0;
}
